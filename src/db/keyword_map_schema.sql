-- Keyword Map for SEO/AEO Writer agent (#2)
-- Shared keyword pool across all products with cooldown tracking

CREATE TABLE IF NOT EXISTS keyword_map (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  account_id UUID NOT NULL REFERENCES accounts(id),
  keyword TEXT NOT NULL,
  product_assigned TEXT NOT NULL,
  search_volume_estimate INTEGER DEFAULT 0,
  difficulty_estimate INTEGER DEFAULT 50 CHECK (difficulty_estimate BETWEEN 0 AND 100),
  last_used TIMESTAMPTZ,
  next_eligible TIMESTAMPTZ,
  status TEXT DEFAULT 'available' CHECK (status IN ('available', 'used', 'exhausted', 'pre_approved')),
  created_at TIMESTAMPTZ DEFAULT NOW(),

  UNIQUE (account_id, keyword, product_assigned)
);

ALTER TABLE keyword_map ENABLE ROW LEVEL SECURITY;

CREATE POLICY "keyword_map_account_isolation" ON keyword_map
  USING (account_id = current_setting('app.account_id', true)::uuid);

CREATE INDEX idx_keyword_map_product ON keyword_map(account_id, product_assigned, status);
CREATE INDEX idx_keyword_map_volume ON keyword_map(search_volume_estimate DESC);

